--- @class DoableTextureItem
--- @field create fun(texture_name):DoableTextureItem

--- @type DoableTextureItem
DoableTextureItem = Class()

---@param texture Texture
function DoableTextureItem:create(texture)
    local texture_item = setmetatable({}, self)
