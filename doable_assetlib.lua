--- Asset (stored in slot)
--- @class DoableAsset
--- @field currently_active boolean
--- @field name string
--- @field slot_name string
--- @field model_parts table<ModelPart>
--- @field display_item string
--- @field display_text string
--- @field save boolean
--- @field callbacks table<string, function>
--- @field persistent_animations table<Animation>
--- @field setDisplay fun(self, display_text, display_item):DoableAsset
--- @field create fun(name, slot_name):DoableAsset
--- @field enable fun(self, state):DoableAsset
--- @field setModelParts fun(...):DoableAsset
--- @field setAnimations fun(...):DoableAsset
--- @field setOnPet fun(self, on_pet_callback):DoableAsset
--- @field setNeverSaveToConfig fun(self):DoableAsset

--- @type DoableAsset
DoableAsset = Class()

--- DO NOT CALL it manually.
function DoableAsset:create(name, slot_name)
    local asset = setmetatable({
        currently_active = true,
        slot_name = slot_name,
        display_item = "minecraft:glass_pane",
        display_text = "UNKNOWN",
        name = name,
        persistent_animations = {},
        model_parts = {},
        save = true,
        callbacks = {},
    }, self)
    return asset
end

--- Enables or disables an asset's model parts,
--- visibly hiding the model parts.
---
--- ## USAGE:
--- Use only on asset creation, else
--- there will be a desync.
---
--- ## EXAMPLE:
---
--- asset:enable(false)
function DoableAsset:enable(state)
    if self.model_parts == nil then return self end
    for _, model_part in ipairs(self.model_parts) do
        model_part:setVisible(state)
    end
    return self
end

--- Sets display text, display item
--- for an asset in action wheel generated by doable_assetlib_wheel.lua
---
--- ## USAGE:
--- Use only an asset creation.
function DoableAsset:setDisplay(display_text, display_item)
    self.display_item = display_item
    self.display_text = display_text
    return self
end

--- Sets model parts this asset will
--- manage. Best to use unique model parts
--- that aren't managed in any other way,
--- except by DoableAssetLib.
---
--- ## USAGE:
--- Use only on asset creation.
---
--- ## EXAMPLE:
---
--- asset:setModelParts({models.my_model.BestPart, models.my_model.Head})
function DoableAsset:setModelParts(...)
    self.model_parts = ...
    return self
end

--- Sets a callback that happens when the
--- asset is toggled on or off.
---
--- ## USAGE:
--- Use only on asset creation.
---
--- ## EXAMPLE:
---
--- asset:setOnToggle(function (self, toggleState)
--- print(toggleState)
--- end)
function DoableAsset:setOnToggle(on_toggle_callback)
    DoableCallbacksCache.on_toggle[tostring(self.name)] = true
    self.callbacks.on_toggle = on_toggle_callback
    return self
end

--- Sets persistent animations that get
--- enabled or disabled when the asset
--- is enabled or disabled.
---
--- ## USAGE:
--- Use only on asset creation.
---
--- ## EXAMPLE:
--- asset:setAnimations({animations.my_model.Dance, animations.my_model.Jump})
function DoableAsset:setAnimations(...)
    self.persistent_animations = ...
    return self
end

--- Sets what happens when host is
--- being pat if you have a compatible pat script
---
--- ## USAGE:
---
--- For example, with AuriaPat, ensure
--- DoableCallCallbacks("on_pet") is placed
--- inside AuriaPat's local playerEvents table:
---
--- oncePat = {
---   --function(entity) end
---   function(isPetted)
---      DoableCallCallbacks("on_pet")
---   end
---}
---
--- With other PatPat type of scripts, generally,
--- ensure DoableCallCallbacks("on_pet") is called
--- once per pat.
---
--- ## EXAMPLE:
---
--- asset:setOnPet(function (self) print("yes") end)
function DoableAsset:setOnPet(on_pet_callback)
    DoableCallbacksCache.on_pet[tostring(self.name)] = true
    self.callbacks.on_pet = on_pet_callback
    return self
end

--- Marks asset as not save-able to config.
---
--- ## USAGE:
--- Use on asset creation only.
---
--- ## EXAMPLE:
--- asset:setNeverSaveToConfig()
function DoableAsset:setNeverSaveToConfig()
    self.save = false
    return self
end

