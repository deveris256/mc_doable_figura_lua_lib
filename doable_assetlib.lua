--- Manages assets.
--- @class DoableAssetManager
--- @field Assets table<string, DoableAsset>
--- @field CreateAsset fun(self, slot_name, assetName):DoableAsset

--- @type DoableAssetManager
DoableAssetManager = Class()
DoableAssetManager.Assets = {}

--- Creates an asset
---
--- ## USAGE
--- Use if you want to create an asset.
--- Best to use short IDs for smaller pings!
---
--- ## EXAMPLE:
--- If slot name is 1 and asset id is 2 go about it like:
--- DoableAssetManager:createAsset(1, 2)
function DoableAssetManager:CreateAsset(slot_name, asset_id)
    local asset = DoableAsset:create(tostring(asset_id), tostring(slot_name))
    rawset(self.Assets, tostring(asset_id), asset)
    return asset
end

--- Manages slots.
--- @class DoableSlotManager
--- @field Slots table<string, DoableSlot>
--- @field LoadAllFromConfig fun(self):DoableSlotManager
--- @field saveSlotToConfig fun(self, slot_name):DoableSlotManager
--- @field markForUpdate fun(self, slot_name):DoableSlotManager
--- @field markAllForUpdate fun(self):DoableSlotManager

--- @type DoableSlotManager
DoableSlotManager = Class()
DoableSlotManager.Slots = setmetatable({}, {
    __index = function(self, slot_name)
        local subtable = DoableSlot:create()
        rawset(self, tostring(slot_name), subtable)
        return subtable
    end
})

function DoableSlotManager:saveSlotToConfig(slot_name, asset_name)
    local old_config_name = config:getName()
    config:setName("DoableAssetLib_" .. DoableConfig.DoableConfig.config_basename)

    if asset_name == nil then
        asset_name = no_outfit
    end

    config:save(
        slot_name,
        asset_name
    )
    config:setName(old_config_name)
    return self
end

function DoableSlotManager:LoadAllFromConfig()
    local old_config_name = config:getName()
    config:setName("DoableAssetLib_" .. DoableConfig.DoableConfig.config_basename)

    for slot_name, outfit in pairs(config:load()) do
        if outfit == no_outfit then
            outfit = nil
        end

        local slot_name = tostring(slot_name)
        local outfit = tostring(outfit)

        self.Slots[slot_name].force_update = true
        self.Slots[slot_name]:setAsset(outfit)
    end

    config:setName(old_config_name)
    return self
end

function DoableCallCallbacks(callback_name)
    if DoableCallbacksCache[callback_name] == nil then return end

    for slot_name, slot in pairs(DoableSlotManager.Slots) do
        if slot.asset ~= nil then
            if DoableCallbacksCache[callback_name][slot.asset] ~= nil then
                local asset = DoableAssetManager.Assets[slot.asset]

                pcall(asset.callbacks[callback_name], asset)
            end
        end
    end
end

